import { join } from "node:path";
import type { AppExtensionIndexEntry } from "../project-index/index.js";
import { writeGeneratedFile, type GeneratedFileResult } from "./write-generated-file.js";

export interface AppExtensionsGenerationResult {
  file: GeneratedFileResult;
  warnings: string[];
}

export async function generateAppExtensionsDts(
  rootDir: string,
  entries: AppExtensionIndexEntry[],
  options: { checkOnly?: boolean } = {},
): Promise<AppExtensionsGenerationResult> {
  const filePath = join(
    rootDir,
    "src",
    "types",
    "generated",
    "app-extensions.generated.d.ts",
  );

  const warnings: string[] = [];
  const merged = new Map<string, string>();

  for (const entry of entries) {
    const existing = merged.get(entry.propertyKey);
    if (!existing) {
      merged.set(entry.propertyKey, entry.inferredTypeText);
      continue;
    }

    if (existing !== entry.inferredTypeText) {
      warnings.push(
        `Conflicting inferred types for app.extend("${entry.propertyKey}") in ${entry.pluginFile}; falling back to unknown.`,
      );
      merged.set(entry.propertyKey, "unknown");
    }
  }

  const lines = [
    "// Auto-generated by vext typegen (experimental). DO NOT EDIT.",
    "",
    'declare module "vextjs" {',
    "  interface VextApp {",
    ...[...merged.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, typeText]) => `    ${key}: ${typeText};`),
    "  }",
    "}",
    "",
  ];

  return {
    file: await writeGeneratedFile(filePath, lines.join("\n"), options),
    warnings,
  };
}

