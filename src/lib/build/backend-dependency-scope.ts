import path from "node:path";
import type { ArtifactCandidate } from "../project/artifact-transaction.js";
import { isPathInside } from "../path-boundary.js";

export const BACKEND_DEPENDENCY_SCOPE = ".vext-dependencies.cjs";
export const EXTERNAL_PRELOAD_PAYLOAD_DIR = ".vext-preload";

/** 外部产物保留服务目录的依赖身份；部署时整体保留服务与产物的相对位置。 */
export function needsBackendDependencyScope(
  rootDir: string,
  outDir: string,
): boolean {
  return !isPathInside(rootDir, outDir, true);
}

/**
 * 运行时辅助文件与后端代码共同提交，不写 node_modules、不改 NODE_PATH。
 * 仅已编译文件参与映射；依赖包、前端 bundle 和其他服务仍由各自的 Node 规则解析。
 */
export function backendDependencyScopeArtifact(
  outDir: string,
  artifacts: readonly ArtifactCandidate[],
): ArtifactCandidate {
  const sources = artifacts
    .filter((file) => file.source && /\.(?:js|mjs|cjs)$/u.test(file.path))
    .map((file) => [
      path.relative(outDir, file.path).replaceAll("\\", "/"),
      path.relative(outDir, file.source!).replaceAll("\\", "/"),
    ])
    .sort(([a], [b]) => a!.localeCompare(b!));
  // 同一 resolve 实现供新 Node 的同步 hook 与 Node 20/22.12 的异步 hook 使用。
  const resolver = `function key(url) {
    const parsed = new URL(url);
    parsed.search = "";
    parsed.hash = "";
    return process.platform === "win32" ? parsed.href.toLowerCase() : parsed.href;
  }
  function resolveDependency(specifier, context, nextResolve) {
    const source = context.parentURL && sources.get(key(context.parentURL));
    const bare = !/^(?:\\.{1,2}(?:\\/|$)|[\\/\\\\]|[a-zA-Z][a-zA-Z\\d+.-]*:)/u.test(specifier);
    return nextResolve(specifier, source && bare ? { ...context, parentURL: source } : context);
  }`;
  const hook = `let sources;
    export function initialize(entries) { sources = new Map(entries); }
    ${resolver}
    export { resolveDependency as resolve };`;
  return {
    path: path.join(outDir, BACKEND_DEPENDENCY_SCOPE),
    contents: `// Generated by VextJS. Owned by the backend artifact transaction.
const { createRequire, register, registerHooks } = require("node:module");
const { resolve } = require("node:path");
const { pathToFileURL } = require("node:url");
${resolver}
const sources = new Map(${JSON.stringify(sources)}.map(([output, source]) => [
  key(pathToFileURL(resolve(__dirname, output)).href),
  pathToFileURL(resolve(__dirname, source)).href,
]));
if (typeof registerHooks === "function") {
  registerHooks({ resolve: resolveDependency });
} else {
  register(${JSON.stringify(`data:text/javascript,${encodeURIComponent(hook)}`)} + "#" + encodeURIComponent(pathToFileURL(__filename).href), { data: [...sources] });
}
module.exports = function bindDependencyScope(target) {
  const source = sources.get(key(pathToFileURL(target.filename).href));
  if (source) target.paths = createRequire(source).resolve.paths("vext-dependency-scope");
};
`,
  };
}
